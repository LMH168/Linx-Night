import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { addPlayer, appendEvent, assignRoles, createRoom, fillAiSeats, loadSnapshot, privateState, publicState, saveSnapshot, CAMPS, PLAYER_TYPES, ROLES } from '../src/model.mjs';

const room = createRoom({ roomId: 'room_test', hostPlayerId: 'p1' });
addPlayer(room, { playerId: 'p1', displayName: '真人 1' });
assert.throws(() => addPlayer(room, { playerId: 'p1', displayName: '重复' }), /already joined/);
fillAiSeats(room);
assert.equal(room.seats.length, 9);
assert.equal(room.seats.filter(seat => seat.playerType === PLAYER_TYPES.AI).length, 8);
assignRoles(room);
assert.equal(room.seats.filter(seat => seat.role === ROLES.WEREWOLF).length, 3);
assert.equal(room.seats.filter(seat => seat.role === ROLES.SEER).length, 1);
assert.equal(room.seats.filter(seat => seat.role === ROLES.WITCH).length, 1);
assert.equal(room.seats.filter(seat => seat.role === ROLES.HUNTER).length, 1);
assert.equal(room.seats.filter(seat => seat.camp === CAMPS.GOOD).length, 6);
const mine = privateState(room, 'p1');
const visible = publicState(room);
assert.equal(visible.seats[0].role, undefined);
assert.equal(visible.seats[0].camp, undefined);
assert.equal(mine.playerId, 'p1');
assert.throws(() => privateState(room, 'missing'), /not found/);
appendEvent(room, { eventId: 'evt_test', type: 'room.updated', data: { ok: true } });
assert.throws(() => appendEvent(room, { eventId: 'evt_test', type: 'room.updated' }), /duplicate event/);
const dir = await mkdtemp(join(tmpdir(), 'linx-night-'));
const file = join(dir, 'room.json');
await saveSnapshot(room, file);
const restored = await loadSnapshot(file);
assert.deepEqual(restored, room);
await rm(dir, { recursive: true, force: true });
console.log('domain model tests passed');
