import assert from 'node:assert/strict';
import { createRoom, addPlayer, publicState, assignRoles } from '../src/model.mjs';
import { submitVote } from '../src/engine.mjs';
const room = createRoom({ roomId: 'vote_state_room', hostPlayerId: 'p1' });
for (let index = 1; index <= 9; index += 1) addPlayer(room, { playerId: `p${index}`, displayName: `玩家${index}` });
assignRoles(room);
room.phase = 'VOTE'; room.round = 1; room.seats.forEach(seat => { seat.alive = true; });
submitVote(room, 'P1', 'P2', 'vote-1');
let state = publicState(room);
assert.deepEqual(state.submittedVoteSeatIds, ['P1']);
assert.equal(state.submittedVoteRound, 1);
assert.equal(JSON.stringify(state).includes('P2'), true);
assert.equal(JSON.stringify(state).includes('targetSeatId'), false);
assert.throws(() => submitVote(room, 'P1', 'P3', 'vote-2'), /already voted/);
assert.deepEqual(publicState(room).submittedVoteSeatIds, ['P1']);
for (let index = 2; index <= 9; index += 1) submitVote(room, `P${index}`, 'P2', `vote-${index}`);
state = publicState(room);
assert.deepEqual(state.submittedVoteSeatIds, []);
assert.equal(state.submittedVoteRound, null);
assert.equal(room.voteResolutions.length, 1);
console.log('vote state projection tests passed');
