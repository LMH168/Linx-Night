import assert from 'node:assert/strict';
import { createApiServer, rooms } from '../src/api.mjs';
const { server } = createApiServer({ port: 0 });
await new Promise(resolve => server.listen(0, resolve));
const port = server.address().port;
const request = (path, options = {}) => fetch(`http://127.0.0.1:${port}${path}`, { headers: { 'content-type': 'application/json', ...(options.headers || {}) }, ...options });
const created = await request('/api/rooms', { method: 'POST', body: JSON.stringify({ player_id: 'config-host', display_name: '房主' }) });
const room = await created.json();
const notFull = await request(`/api/rooms/${room.room_id}/start`, { method: 'POST', headers: { 'x-player-id': 'config-host' } });
assert.equal(notFull.status, 409);
assert.deepEqual((await notFull.json()).error, { code: 'ROOM_NOT_FULL', message: 'room is not full: 1 occupied, 8 missing', occupied: 1, missing: 8 });
const denied = await request(`/api/rooms/${room.room_id}/players`, { method: 'POST', headers: { 'x-player-id': 'stranger' }, body: JSON.stringify({ player_type: 'ai', display_name: '不应添加' }) });
assert.equal(denied.status, 403);
const added = await request(`/api/rooms/${room.room_id}/players`, { method: 'POST', headers: { 'x-player-id': 'config-host' }, body: JSON.stringify({ player_type: 'ai', display_name: '侦探小七' }) });
assert.equal(added.status, 201);
const addedBody = await added.json();
assert.equal(addedBody.player.playerType, 'ai');
const seatId = addedBody.player.seatId;
const renamed = await request(`/api/rooms/${room.room_id}/players/${seatId}`, { method: 'PATCH', headers: { 'x-player-id': 'config-host' }, body: JSON.stringify({ display_name: '新名字' }) });
assert.equal(renamed.status, 200);
assert.equal((await renamed.json()).player.displayName, '新名字');
const renameDenied = await request(`/api/rooms/${room.room_id}/players/${seatId}`, { method: 'PATCH', headers: { 'x-player-id': 'stranger' }, body: JSON.stringify({ display_name: '越权' }) });
assert.equal(renameDenied.status, 403);
for (let index = 0; index < 7; index += 1) await request(`/api/rooms/${room.room_id}/players`, { method: 'POST', headers: { 'x-player-id': 'config-host' }, body: JSON.stringify({ player_type: 'ai', display_name: `AI ${index}` }) });
const fullStart = await request(`/api/rooms/${room.room_id}/start`, { method: 'POST', headers: { 'x-player-id': 'config-host' } });
assert.equal(fullStart.status, 202);
await new Promise(resolve => setImmediate(resolve));
assert.equal(rooms.get(room.room_id).seats.length, 9);
const renameAfterStart = await request(`/api/rooms/${room.room_id}/players/${seatId}`, { method: 'PATCH', headers: { 'x-player-id': 'config-host' }, body: JSON.stringify({ display_name: '太晚了' }) });
assert.equal(renameAfterStart.status, 409);
rooms.clear();
server.close();
console.log('room configuration tests passed');
